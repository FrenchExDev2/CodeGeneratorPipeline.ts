const watchers = vi.hoisted(() => ({ watch: vi.fn() }));
vi.mock('chokidar', () => watchers);

async function withProject(work: (root: string, configuration: (value: number, severity?: string) => Promise<void>) => Promise<void>) {
  const root = await mkdtemp(join(tmpdir(), 'sourcegen-cli-é-'));
  const configuration = async (value: number, severity = 'info') => {
    await writeFile(join(root, 'sourcegen.config.mjs'), `
import {createHash} from 'node:crypto';
const body='export const value = ${value};\\n';
const contents=['// <auto-generated>', '// GENERATED BY @frenchexdev2/ts-codegen-pipeline — DO NOT EDIT',
 '// producer: demo  iteration: 0  contentHash: sha256:'+createHash('sha256').update(body).digest('hex').slice(0,12), '// </auto-generated>', body].join('\\n');
export default { consumerPackageRoot:${JSON.stringify(root)}, tsconfigPath:${JSON.stringify(join(root, 'tsconfig.json'))},
 generators:[{id:'demo',async execute(ctx){
  ctx.logger.info('generator info'); ctx.logger.warn('generator warning');
  const emission=ctx.virtFs.addSource({relPath:'value.generated.ts',contents,producerId:'demo'});
  return {emittedSomething:emission.newOrChanged,diagnostics:emission.diagnostics??[]};
 }}], analyzers:[{id:'analyzer:generator-id-non-empty',description:'Description visible',docsUrl:'https://example.test/rule',
 analyze(){return [{code:'TEST',severity:${JSON.stringify(severity)},message:'diagnostic visible',producerId:'demo'}]}}]
};`, 'utf8');
  };
  try {
    await mkdir(join(root, 'src')); await writeFile(join(root, 'src/input.ts'), 'export const input = 1;', 'utf8');
    await writeFile(join(root, 'tsconfig.json'), JSON.stringify({ compilerOptions: { target: 'ES2022', module: 'ESNext', moduleResolution: 'bundler', skipLibCheck: true }, include: ['src/**/*.ts'] }), 'utf8');
    await configuration(1); await work(root, configuration);
  } finally { await rm(root, { recursive: true, force: true }); }
}

async function captured(root: string, work: (out: string[], errors: string[]) => Promise<void>) {
  const out: string[] = [], errors: string[] = [], previous = process.exitCode;
  process.exitCode = 0;
  const mocks = [vi.spyOn(process, 'cwd').mockReturnValue(root),
    vi.spyOn(console, 'log').mockImplementation((...values: unknown[]) => { out.push(values.map(String).join(' ')); }),
    vi.spyOn(console, 'warn').mockImplementation((...values: unknown[]) => { errors.push(values.map(String).join(' ')); }),
    vi.spyOn(console, 'error').mockImplementation((...values: unknown[]) => { errors.push(values.map(String).join(' ')); })];
  try { await work(out, errors); return { out: out.join('\n'), errors: errors.join('\n'), code: Number(process.exitCode ?? 0) }; }
  finally { for (const mock of mocks) mock.mockRestore(); process.exitCode = previous; }
}
const command = (root: string, args: string[]) => captured(root, async () => {
  await createSourcegenProgram().exitOverride().parseAsync(['node', 'sourcegen', ...args, '-c', join(root, 'sourcegen.config.mjs')]);
});

@FeatureTest(AnalyzerCliFeature, { timeout: 120_000 })
class SourcegenCliDispatchContracts {
  @Verifies<AnalyzerCliFeature>('dispatchesActualCommandsWithDomainExitCodes')
  async dispatchesActualCommandsWithDomainExitCodes() {
    expect(createSourcegenProgram()).not.toBe(createSourcegenProgram());
    await withProject(async (root, configuration) => {
      const run = await command(root, ['run', '--json']);
      expect(run.code, run.errors).toBe(0); expect(JSON.parse(run.out)).toMatchObject({ ok: true, committed: true });
      expect(run.errors).toContain('generator info'); expect(run.errors).toContain('generator warning');
      const verify = await command(root, ['verify', '--json']);
      expect(verify.code, verify.errors).toBe(0); expect(JSON.parse(verify.out).ok).toBe(true);
      const original = await readFile(join(root, 'generated/value.generated.ts'), 'utf8');
      await writeFile(join(root, 'generated/value.generated.ts'), 'export const changed = true;', 'utf8');
      const drift = await command(root, ['verify', '--json']);
      expect(drift.code).toBe(2); expect(JSON.parse(drift.out).ok).toBe(false);
      await writeFile(join(root, 'generated/value.generated.ts'), original, 'utf8');
      await configuration(1, 'error');
      const rejected = await command(root, ['run', '--no-color']);
      expect(rejected.code).toBe(1); expect(rejected.out).toContain('diagnostic visible');
      const invalid = await command(root, ['verify', '--json']);
      expect(invalid.code).toBe(1); expect(JSON.parse(invalid.out).ok).toBe(false);
      await rm(join(root, 'sourcegen.config.mjs'));
      for (const route of ['run', 'verify', 'analyze', 'list', 'explain']) {
        const result = await command(root, route === 'list' ? [route, 'analyzers'] : route === 'explain' ? [route, 'AN0100'] : [route]);
        expect(result.code).toBe(1); expect(result.errors).toContain('config not found');
      }
      await writeFile(join(root, 'sourcegen.config.mjs'), 'export default {};', 'utf8');
      expect((await command(root, ['run'])).errors).toContain('did not export a SourceGenConfig');
      const startup = await captured(root, async () => { await main(['node', 'sourcegen', '--', 'run', '-c', 'absent.mjs']); });
      expect(startup.code).toBe(1); expect(startup.errors).toContain('config not found');
    });
  }

  @Verifies<AnalyzerCliFeature>('actualAnalyzerQueriesResolveAndRejectUnknownTargets')
  async actualAnalyzerQueriesResolveAndRejectUnknownTargets() {
    await withProject(async (root, configuration) => {
      const list = await command(root, ['list', 'analyzers']);
      expect(list.code).toBe(0); expect(list.out).toContain('Description visible');
      for (const id of ['AN0100', 'analyzer:generator-id-non-empty']) {
        const explain = await command(root, ['explain', id]);
        expect(explain.code).toBe(0); expect(explain.out).toContain('https://example.test/rule');
      }
      expect((await command(root, ['explain', 'UNKNOWN'])).code).toBe(1);
      expect((await command(root, ['explain', 'AN0120'])).code).toBe(1);
      expect((await command(root, ['list', 'unknown'])).code).toBe(1);
      expect((await command(root, ['analyze', '--only', 'absent'])).code).toBe(1);
      const analyzed = await command(root, ['analyze', '--only', 'analyzer:generator-id-non-empty', '--json']);
      expect(analyzed.code).toBe(0); expect(JSON.parse(analyzed.out).diagnostics[0].code).toBe('TEST');
      await expect(readFile(join(root, 'generated/value.generated.ts'), 'utf8')).rejects.toMatchObject({ code: 'ENOENT' });
      await configuration(3, 'error');
      const error = await command(root, ['analyze', '--no-color']);
      expect(error.code).toBe(1); expect(error.out).toContain('diagnostic visible');
      await writeFile(join(root, 'sourcegen.config.mjs'), `export const consumerPackageRoot=${JSON.stringify(root)}; export const tsconfigPath=${JSON.stringify(join(root, 'tsconfig.json'))}; export const generators=[];`, 'utf8');
      expect((await command(root, ['list', 'analyzers'])).out).toContain('no analyzers registered');
      expect((await command(root, ['analyze', '--json'])).code).toBe(0);
    });
  }
}

@FeatureTest(WatchModeFeature, { timeout: 120_000 })
class SourcegenWatchLifecycleContracts {
  @Verifies<WatchModeFeature>('cliReloadsConfigAndAwaitsWatcherShutdown')
  async cliReloadsConfigAndAwaitsWatcherShutdown() {
    await withProject(async (root, configuration) => {
      const listeners = new Map<string, (file: string) => void>();
      let releaseClose!: () => void, closed = false, shutdown!: () => void;
      const closing = new Promise<void>(resolve => { releaseClose = resolve; });
      const watcher = { on: vi.fn((event: string, listener: (file: string) => void) => { listeners.set(event, listener); return watcher; }),
        close: vi.fn(async () => { await closing; closed = true; }) };
      watchers.watch.mockReturnValue(watcher);
      const originalOnce = process.once;
      const signal = vi.spyOn(process, 'once').mockImplementation(((event: string, listener: () => void) => {
        if (event === 'SIGINT') { shutdown = listener; return process; }
        return originalOnce.call(process, event, listener);
      }) as typeof process.once);
      try {
        await captured(root, async (out, errors) => {
          await createSourcegenProgram().parseAsync(['node', 'sourcegen', 'watch', '-c', join(root, 'sourcegen.config.mjs'), '-d', '1', '--no-color']);
          expect(await readFile(join(root, 'generated/value.generated.ts'), 'utf8')).toContain('value = 1');
          expect(watchers.watch).toHaveBeenCalled();
          const options = watchers.watch.mock.calls.at(-1)![1];
          expect(options.ignoreInitial).toBe(true); expect(options.ignored(join(root, 'node_modules/value.ts'))).toBe(true);
          listeners.get('change')!(join(root, 'notes.md'));
          await configuration(2);
          listeners.get('add')!(join(root, 'src/new.ts'));
          const deadline = Date.now() + 30_000;
          while (Date.now() < deadline && !(await readFile(join(root, 'generated/value.generated.ts'), 'utf8')).includes('value = 2')) await setTimeout(25);
          expect(await readFile(join(root, 'generated/value.generated.ts'), 'utf8'), JSON.stringify({ out, errors })).toContain('value = 2');
          await rm(join(root, 'sourcegen.config.mjs'));
          listeners.get('unlink')!(join(root, 'src/new.ts'));
          while (Date.now() < deadline && !errors.some(message => message.includes('config not found'))) await setTimeout(25);
          expect(errors.join('\n')).toContain('config not found'); expect(out.join('\n')).toContain('[watch]');
          process.exitCode = 7; shutdown(); await setTimeout(0);
          expect(watcher.close).toHaveBeenCalledOnce(); expect(closed).toBe(false); expect(process.exitCode).toBe(7);
          releaseClose(); await setTimeout(0); expect(closed).toBe(true); expect(process.exitCode).toBe(0);
        });
      } finally { releaseClose(); signal.mockRestore(); watchers.watch.mockReset(); }
    });
  }
}
