import { FeatureTest, Verifies } from '@frenchexdev2/requirements-shared-kernel';
import { expect } from 'vitest';
import { GeneratedFileBannerFeature } from '../../requirements/features/generated-file-banner.js';
import { withBanner, extractBody, extractMeta, verifyBanneredHash, sha256Short } from '../../src/emit/banner.js';

@FeatureTest(GeneratedFileBannerFeature)
class GeneratedFileBannerTests {
  @Verifies<GeneratedFileBannerFeature>('bannerHasFourLineEnvelope')
  fourLineEnvelope() {
    const out = withBanner('export const x = 1;\n', { producerId: 'gen.a' });
    const lines = out.split('\n');
    expect(lines[0]).toBe('// <auto-generated>');
    expect(lines[1]).toBe('// GENERATED BY @frenchexdev2/ts-codegen-pipeline — DO NOT EDIT');
    expect(lines[3]).toBe('// </auto-generated>');
  }

  @Verifies<GeneratedFileBannerFeature>('bannerCarriesProducerAndIteration')
  carriesProducerIteration() {
    const out = withBanner('body', { producerId: 'sourcegen.companion', iteration: 7 });
    const meta = extractMeta(out);
    expect(meta.producerId).toBe('sourcegen.companion');
    expect(meta.iteration).toBe(7);
    expect(out.split('\n')[2]).toBe(`// producer: sourcegen.companion  iteration: 7  contentHash: sha256:${sha256Short('body')}`);
    expect(extractMeta(withBanner('body', { producerId: 'g' })).iteration).toBe(0);
    for (const iteration of [-1, 1.5, NaN, Infinity, Number.MAX_SAFE_INTEGER + 1]) expect(() => withBanner('body', { producerId: 'g', iteration })).toThrow(RangeError);
  }

  @Verifies<GeneratedFileBannerFeature>('bannerHasNoTimestampOrRandomness')
  unchangedEmissionsKeepTheirOriginalCreationIteration() {
    const first = withBanner('body', { producerId: 'g', iteration: 2 });
    expect(withBanner('body', { producerId: 'g', iteration: 99 }, first)).toBe(first);
    const changed = withBanner('changed', { producerId: 'g', iteration: 3 }, first);
    expect(extractMeta(changed).iteration).toBe(3);
    expect(extractBody(changed)).toBe('changed');
    expect(extractMeta(withBanner('body', { producerId: 'other', iteration: 4 }, first)).producerId).toBe('other');
    expect(extractMeta(withBanner('body', { producerId: 'g', iteration: 5 }, 'invalid')).iteration).toBe(5);
    expect(extractMeta(withBanner('body', { producerId: 'g', iteration: 6 }, first.replace('body', 'tampered'))).iteration).toBe(6);
  }

  @Verifies<GeneratedFileBannerFeature>('bannerCarriesSha256ContentHash')
  carriesSha256() {
    const body = 'export const x = 42;\n';
    const out = withBanner(body, { producerId: 'g' });
    const meta = extractMeta(out);
    expect(meta.contentHash).toMatch(/^[0-9a-f]{12}$/);
    expect(meta.contentHash).toBe(sha256Short(body));
  }

  @Verifies<GeneratedFileBannerFeature>('bannerHasNoTimestampOrRandomness')
  noTimestamp() {
    const a = withBanner('body', { producerId: 'g' });
    const b = withBanner('body', { producerId: 'g' });
    expect(a).toBe(b);
    // Also check that no `Date` or epoch-like substring appears.
    expect(a).not.toMatch(/\d{10}/);  // unix epoch
    expect(a).not.toMatch(/T\d\d:/);  // ISO timestamp marker
  }

  @Verifies<GeneratedFileBannerFeature>('bannerRoundTripPreservesBody')
  roundTripPreservesBody() {
    const body = 'export class Foo {\n  bar(): number { return 1; }\n}\n';
    const wrapped = withBanner(body, { producerId: 'g' });
    expect(extractBody(wrapped)).toBe(body);
  }

  @Verifies<GeneratedFileBannerFeature>('contentHashSelfConsistent')
  hashSelfConsistent() {
    const body = 'arbitrary body';
    const wrapped = withBanner(body, { producerId: 'g' });
    expect(verifyBanneredHash(wrapped)).toBe(true);
  }
}

export { GeneratedFileBannerTests };
