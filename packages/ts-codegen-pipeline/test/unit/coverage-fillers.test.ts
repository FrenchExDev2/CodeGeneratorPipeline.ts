@FeatureTest(AtomicCommitFeature)
class CommitErrorPaths {
  @Verifies<AtomicCommitFeature>('failedRenameLeavesNoTmpFiles')
  async writeFilePhase1Failure() {
    // Force fsp.writeFile to throw by giving an emission whose dirname creation
    // collides with an existing FILE on disk (mkdir on a path that's a file fails).
    const outDir = fs.mkdtempSync(path.join(os.tmpdir(), 'tscp-cov-'));
    fs.writeFileSync(path.join(outDir, 'sub'), 'i am a file, not a dir');
    let threw = false;
    try {
      await commitTo({
        outDir,
        emissions: [{ relPath: 'sub/Inside.generated.ts', contents: 'X' }],
        preCommitFiles: [],
      });
    } catch {
      threw = true;
    }
    expect(threw).toBe(true);
    // No .tmp leftovers.
    const entries = fs.readdirSync(outDir);
    expect(entries.some(e => e.endsWith('.tmp'))).toBe(false);
    fs.rmSync(outDir, { recursive: true, force: true });
  }

  @Verifies<AtomicCommitFeature>('commitPurgesObsoleteOutputs')
  async scanHandlesNestedDirAndUnreadable() {
    const outDir = fs.mkdtempSync(path.join(os.tmpdir(), 'tscp-cov-scan-'));
    fs.mkdirSync(path.join(outDir, 'nested'));
    fs.writeFileSync(path.join(outDir, 'nested', 'X.generated.ts'), 'x');
    fs.writeFileSync(path.join(outDir, 'plain.txt'), 'not generated');
    const found = await scanExistingGeneratedFiles(outDir);
    expect(found).toHaveLength(1);
    expect(found[0]?.endsWith('X.generated.ts')).toBe(true);
    fs.rmSync(outDir, { recursive: true, force: true });
    // Non-existent dir → empty array (also exercises the missing-dir branch).
    expect(await scanExistingGeneratedFiles(path.join(os.tmpdir(), 'definitely-not-here-' + Date.now()))).toEqual([]);
  }

  @Verifies<AtomicCommitFeature>('commitPurgesObsoleteOutputs')
  async purgeUnlinkOnAlreadyMissing() {
    // preCommitFiles lists a file that doesn't exist on disk → unlink fails silently.
    const outDir = fs.mkdtempSync(path.join(os.tmpdir(), 'tscp-cov-purge-'));
    const ghostPath = path.join(outDir, 'ghost.generated.ts');
    const result = await commitTo({
      outDir,
      emissions: [{ relPath: 'real.generated.ts', contents: 'real' }],
      preCommitFiles: [ghostPath],
    });
    // ghost was not actually purged (didn't exist) → not in `purged`.
    expect(result.purged).toEqual([]);
    fs.rmSync(outDir, { recursive: true, force: true });
  }
}

