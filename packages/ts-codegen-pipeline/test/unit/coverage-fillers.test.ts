@FeatureTest(GeneratedFileBannerFeature)
class BannerErrorPaths {
  @Verifies<GeneratedFileBannerFeature>('bannerRoundTripPreservesBody')
  extractBodyRejectsBadInput() {
    expect(() => extractBody('not a banner at all')).toThrow();
    expect(() => extractBody('// <auto-generated>\nx\nx\nWRONG_CLOSE\nbody')).toThrow();
  }

  @Verifies<GeneratedFileBannerFeature>('bannerCarriesSha256ContentHash')
  extractMetaRejectsBadInput() {
    expect(() => extractMeta('// not a banner')).toThrow();
    expect(() => extractMeta(['// <auto-generated>', '// header', 'garbage', '// </auto-generated>'].join('\n'))).toThrow();
  }

  @Verifies<GeneratedFileBannerFeature>('contentHashSelfConsistent')
  verifyBanneredHashCatch() {
    // Malformed banner triggers extractBody/extractMeta throws → returns false.
    expect(verifyBanneredHash('garbage')).toBe(false);
    // Tampered hash with valid envelope but mismatched content.
    const tampered = ['// <auto-generated>',
                     '// header',
                     '// producer: g  contentHash: sha256:000000000000',
                     '// </auto-generated>',
                     'real body'].join('\n');
    expect(verifyBanneredHash(tampered)).toBe(false);
  }
}

