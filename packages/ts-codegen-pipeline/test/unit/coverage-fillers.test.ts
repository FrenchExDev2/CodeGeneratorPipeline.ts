@FeatureTest(AtomicCommitFeature)
class NodeFsPortDirect {
  @Verifies<AtomicCommitFeature>('defaultNodeFsPortRoundTripsDiskOperations')
  async nodeFsRoundTrip() {
    const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'tscp-cov-nodefs-'));
    const sub = path.join(tmp, 'sub');
    await nodeFs.mkdir(sub, { recursive: true });
    const a = path.join(sub, 'a.txt');
    const b = path.join(sub, 'b.txt');
    await nodeFs.writeFile(a, 'hello');
    expect(await nodeFs.exists(a)).toBe(true);
    expect(await nodeFs.exists(path.join(sub, 'missing.txt'))).toBe(false);
    expect(await nodeFs.readFile(a, 'utf8')).toBe('hello');
    const st = await nodeFs.stat(a);
    expect(st.size).toBeGreaterThan(0);
    expect(st.isDirectory()).toBe(false);
    expect((await nodeFs.readdir(sub)).includes('a.txt')).toBe(true);
    await nodeFs.rename(a, b);
    expect(await nodeFs.exists(a)).toBe(false);
    expect(await nodeFs.exists(b)).toBe(true);
    expect(nodeFs.unlink).toBeTypeOf('function');
    await nodeFs.unlink!(b);
    expect(await nodeFs.exists(b)).toBe(false);
    fs.rmSync(tmp, { recursive: true, force: true });
  }
}

