import { Requirement, Priority } from '@frenchexdev2/requirements-shared-kernel';
import type { PipelineRequirementStyle } from '../vocabulary.js';

export abstract class ReqTscpWriteOnceRequirement extends Requirement<PipelineRequirementStyle> {
  readonly id = 'REQ-TSCP-WRITE-ONCE';
  readonly title = 'Every emitted file shall carry a banner with producer id, iteration, and a SHA-256 contentHash';
  readonly priority = Priority.High;
  readonly status = 'Approved' as const;
  readonly kind = 'Functional' as const;

  readonly statement = {
    pattern: 'ubiquitous' as const,
    response: 'Each emitted file shall begin with a 4-line banner: `// <auto-generated>` / `// GENERATED BY @frenchexdev2/ts-codegen-pipeline — DO NOT EDIT` / `// producer: <id>  iteration: <n>  contentHash: sha256:<12 hex>` / `// </auto-generated>`. The contentHash is computed over the file body excluding the hash line itself. The `verify` command shall recompute the hash from disk and report `SG0010 GeneratedFileEditedByHand` when it differs.',
  };

  readonly rationale = {
    claim: 'Generated files committed to git are tempting to "just tweak". The banner advertises authorship to humans, the hash makes hand-edits machine-detectable, and the `verify` command fails CI when a file has been modified outside the generator path. The triplet is the only way to keep generated artifacts trustworthy without locking them out of git.',
    kind: 'principle' as const,
    evidence: [
      { kind: 'expert-opinion' as const, expert: 'Stéphane Erard — generated-file integrity policy 2026-05-02', recordedAt: '2026-05-02' },
    ],
  };

  readonly fitCriteria = [
    { kind: 'unit-test' as const,
      describes: 'Round-trip property: `extractBody(withBanner(c, meta)) === c` for arbitrary `c` and `meta`.',
      binds: ['bannerRoundTripPreservesBody'] },
    { kind: 'unit-test' as const,
      describes: 'Hash recomputed over `extractBody(...)` equals the hash advertised in the banner.',
      binds: ['contentHashSelfConsistent'] },
    { kind: 'unit-test' as const,
      describes: 'Edit a generated file by one byte; `sourcegen verify` exits non-zero with SG0010.',
      binds: ['verifyDetectsHandEdit'] },
  ];

  readonly verificationMethod = 'Test' as const;
  readonly source = { type: 'stakeholder' as const, role: 'maintainer', date: '2026-05-02' };
  readonly risk = {
    level: 'Medium' as const,
    ifNotMet: 'Generated files drift from generator outputs; users hand-tweak without trace; CI cannot enforce the "machine-written" boundary.',
  };
}
