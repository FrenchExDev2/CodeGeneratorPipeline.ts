import * as path from 'node:path';
import { Project, ts, type CompilerOptions } from 'ts-morph';
import { buildVirtFs, type VirtFsHandle } from './internal.js';
import { nodeFs, type FileSystemPort } from '../ports/file-system.js';

export interface CreateVirtFsOptions {
  /** Absolute or relative path to the consumer's `tsconfig.json`. */
  readonly tsconfigPath: string;
  /** Absolute path to the consumer package root (used to resolve outDir). */
  readonly consumerPackageRoot: string;
  /** Absolute path to outDir (typically `<consumerRoot>/generated`). */
  readonly outDir: string;
  /** Defaults to nodeFs. Tests inject a stub for deterministic failure paths. */
  readonly fs?: FileSystemPort;
}

/**
 * Build a virtFS seeded from real disk: read the consumer's tsconfig,
 * construct an in-memory ts-morph Project, copy each user-authored source
 * file's text into it (skipping anything under outDir — those are
 * regenerated by the run, never seeded). The real disk is only READ from
 * here on; writes happen exclusively through `commitTo` at fixpoint.
 *
 * `ts.parseJsonConfigFileContent` itself uses `ts.sys` synchronously to
 * read the tsconfig text and expand globs — that's a typescript-internal
 * step we don't route through the port (it's the parsing of OUR config,
 * not generator I/O). All per-source-file reads after that go through
 * the injected port.
 */
export async function createVirtFs(opts: CreateVirtFsOptions): Promise<VirtFsHandle> {
  const fs = opts.fs ?? nodeFs;
  const tsconfigAbs = path.isAbsolute(opts.tsconfigPath)
    ? opts.tsconfigPath
    : path.resolve(opts.consumerPackageRoot, opts.tsconfigPath);
  const outDirAbs = path.isAbsolute(opts.outDir)
    ? opts.outDir
    : path.resolve(opts.consumerPackageRoot, opts.outDir);

  const configFile = ts.readConfigFile(tsconfigAbs, ts.sys.readFile);
  if (configFile.error) {
    const msg = ts.flattenDiagnosticMessageText(configFile.error.messageText, '\n');
    throw new Error(`ts-codegen-pipeline: failed to read tsconfig at ${tsconfigAbs}: ${msg}`);
  }
  const parsed = ts.parseJsonConfigFileContent(
    configFile.config,
    ts.sys,
    path.dirname(tsconfigAbs),
  );

  const project = new Project({
    useInMemoryFileSystem: true,
    compilerOptions: parsed.options as CompilerOptions,
    skipAddingFilesFromTsConfig: true,
  });

  // Skip generated files (by `.generated.ts` suffix) — they're produced
  // fresh each run, never seeded. This works whether outDir is a dedicated
  // 'generated/' directory or 'src/' (in-source barrel).
  for (const realPath of parsed.fileNames) {
    const realPosix = realPath.replace(/\\/g, '/');
    if (realPosix.endsWith('.generated.ts')) continue;
    if (!(await fs.exists(realPath))) continue;
    const text = await fs.readFile(realPath, 'utf8');
    project.createSourceFile(realPath, text, { overwrite: true });
  }

  return buildVirtFs({ project, outDir: outDirAbs });
}
