import * as crypto from 'node:crypto';

const BANNER_OPEN = '// <auto-generated>';
const BANNER_HEADER = '// GENERATED BY @frenchexdev2/ts-codegen-pipeline — DO NOT EDIT';
const BANNER_CLOSE = '// </auto-generated>';
const META_REGEX = /^\/\/\s+producer:\s+(\S+)\s+iteration:\s+(\d+)\s+contentHash:\s+sha256:([0-9a-f]{12})\s*$/;

export interface BannerMeta {
  readonly producerId: string;
  /** Zero-based creation/update iteration; defaults to the initial iteration. */
  readonly iteration?: number;
}

export interface ParsedBanner extends BannerMeta {
  readonly iteration: number;
  readonly contentHash: string;
}

/**
 * Wrap `body` with a 4-line banner whose meta line carries the given
 * `producerId`, creation/update iteration and a SHA-256 contentHash over the
 * body (12 hex chars). Reuse a verified previous banner when body and producer
 * are unchanged: repeated iterations/runs retain their original provenance.
 */
export function withBanner(body: string, meta: BannerMeta, previous?: string): string {
  const iteration = meta.iteration ?? 0;
  if (!Number.isSafeInteger(iteration) || iteration < 0) throw new RangeError('Banner iteration must be a non-negative safe integer.');
  if (previous !== undefined && verifyBanneredHash(previous)) {
    const previousMeta = extractMeta(previous);
    if (previousMeta.producerId === meta.producerId && extractBody(previous) === body) return previous;
  }
  const hash = sha256Short(body);
  const metaLine = `// producer: ${meta.producerId}  iteration: ${iteration}  contentHash: sha256:${hash}`;
  return [BANNER_OPEN, BANNER_HEADER, metaLine, BANNER_CLOSE, body].join('\n');
}

/** Strip the 4-line banner from the top of `banneredContents`, returning the body. */
export function extractBody(banneredContents: string): string {
  const lines = banneredContents.split('\n');
  if (lines.length < 5 || lines[0] !== BANNER_OPEN || lines[3] !== BANNER_CLOSE) {
    throw new Error('extractBody: input does not carry a recognized banner envelope');
  }
  return lines.slice(4).join('\n');
}

/** Parse the meta line of `banneredContents` into producerId / iteration / contentHash. */
export function extractMeta(banneredContents: string): ParsedBanner {
  const lines = banneredContents.split('\n');
  if (lines.length < 4 || lines[0] !== BANNER_OPEN) {
    throw new Error('extractMeta: input does not carry a recognized banner envelope');
  }
  const metaLine = lines[2] as string;
  const m = META_REGEX.exec(metaLine);
  if (!m) {
    throw new Error('extractMeta: meta line malformed');
  }
  return {
    producerId: m[1] as string,
    iteration: Number(m[2]),
    contentHash: m[3] as string,
  };
}

/**
 * True iff the banner's contentHash matches `sha256(extractBody(...))`.
 * Used by `verify` to detect hand-edits.
 */
export function verifyBanneredHash(banneredContents: string): boolean {
  let body: string;
  let meta: ParsedBanner;
  try {
    body = extractBody(banneredContents);
    meta = extractMeta(banneredContents);
  } catch {
    return false;
  }
  return sha256Short(body) === meta.contentHash;
}

export function sha256Short(s: string): string {
  return crypto.createHash('sha256').update(s, 'utf8').digest('hex').slice(0, 12);
}
